#!/usr/bin/env bash
# One-time, idempotent server setup for OmniCourse prod and staging (run as root).
# Re-running it changes nothing that already exists: passwords, env files and keys are kept.
#
#   sudo deploy/server/setup.sh
#
# Afterwards: add each GitHub environment's public deploy key with add-deploy-key.sh, and run
# certbot once DNS points here (see deploy/README.md).
set -euo pipefail

NODE_VERSION=22.22.1
NPM_VERSION=11.21.1
PG_IMAGE=docker.io/library/postgres:18.6
PG_PORT=5433
APP=/opt/omnicourse
HERE="$(cd "$(dirname "$0")" && pwd)"

# env name, public host, API port
ENVS=("prod omnicourses.lamter.cc 3101" "stag stag-omnicourses.lamter.cc 3102")

[[ $EUID -eq 0 ]] || { echo "run as root" >&2; exit 1; }

# 1. A service user without sudo, except the two helpers in /etc/sudoers.d/omnicourse.
id omnicourse >/dev/null 2>&1 || useradd --system --create-home --home-dir /home/omnicourse --shell /bin/bash omnicourse
install -d -o omnicourse -g omnicourse -m 755 "$APP"
install -d -o omnicourse -g omnicourse -m 700 /home/omnicourse/.ssh
install -d -o root -g omnicourse -m 750 /etc/omnicourse
install -d -o omnicourse -g omnicourse -m 700 /var/backups/omnicourse

# 2. Node, pinned. A private copy: the host's own Node is left alone.
if [[ "$("$APP/node/bin/node" -v 2>/dev/null)" != "v$NODE_VERSION" ]]; then
  tmp="$(mktemp -d)"
  curl -fsSL "https://nodejs.org/dist/v$NODE_VERSION/node-v$NODE_VERSION-linux-x64.tar.xz" -o "$tmp/node.tar.xz"
  curl -fsSL "https://nodejs.org/dist/v$NODE_VERSION/SHASUMS256.txt" -o "$tmp/SHASUMS256.txt"
  (cd "$tmp" && grep " node-v$NODE_VERSION-linux-x64.tar.xz\$" SHASUMS256.txt | sed 's/node-v.*/node.tar.xz/' | sha256sum -c -)
  rm -rf "$APP/node" && mkdir -p "$APP/node"
  tar -xJf "$tmp/node.tar.xz" -C "$APP/node" --strip-components=1
  rm -rf "$tmp"
fi
# npm's launcher runs whichever node is first on PATH: make it this one, not the host's.
export PATH="$APP/node/bin:$PATH"
[[ "$(npm -v)" == "$NPM_VERSION" ]] || npm install -g --silent --prefix "$APP/node" "npm@$NPM_VERSION"
chown -R omnicourse:omnicourse "$APP/node"

# 3. PostgreSQL 18.6 in Docker, reachable from this host only.
if [[ ! -f /etc/omnicourse/postgres.password ]]; then
  umask 077; openssl rand -hex 24 > /etc/omnicourse/postgres.password; umask 022
fi
if ! docker inspect omnicourse-db >/dev/null 2>&1; then
  docker run -d --name omnicourse-db --restart unless-stopped \
    -p "127.0.0.1:$PG_PORT:5432" \
    -e POSTGRES_USER=postgres -e "POSTGRES_PASSWORD=$(cat /etc/omnicourse/postgres.password)" \
    -v omnicourse-pgdata:/var/lib/postgresql \
    --memory 1g "$PG_IMAGE" >/dev/null
fi
for _ in $(seq 30); do docker exec omnicourse-db pg_isready -U postgres -q && break; sleep 1; done

# 4. Per environment: database and role, env file, release folders.
for spec in "${ENVS[@]}"; do
  read -r env host port <<<"$spec"
  db="omnicourse_$env"
  envfile="/etc/omnicourse/$env.env"
  if [[ ! -f "$envfile" ]]; then
    pw="$(openssl rand -hex 24)"
    docker exec -i omnicourse-db psql -U postgres -v ON_ERROR_STOP=1 -q <<SQL
CREATE ROLE $db LOGIN PASSWORD '$pw';
CREATE DATABASE $db OWNER $db;
REVOKE ALL ON DATABASE $db FROM PUBLIC;
SQL
    umask 027
    cat >"$envfile" <<ENV
NODE_ENV=production
PORT=$port
LISTEN_HOST=127.0.0.1
TRUST_PROXY=loopback
CORS_ORIGIN=https://$host
DATABASE_URL=postgres://$db:$pw@127.0.0.1:$PG_PORT/$db
ENV
    umask 022
    chown root:omnicourse "$envfile"; chmod 640 "$envfile"
  fi
  install -d -o omnicourse -g omnicourse -m 755 "$APP/$env" "$APP/$env/releases"
done

# 5. Deploy entry point, its root helper, and the sudo rule that allows only those.
install -o root -g root -m 755 "$HERE/omnicourse-deploy" /usr/local/bin/omnicourse-deploy
install -o root -g root -m 755 "$HERE/omnicourse-root" /usr/local/sbin/omnicourse-root
cat >/etc/sudoers.d/omnicourse <<'SUDO'
omnicourse ALL=(root) NOPASSWD: /usr/local/sbin/omnicourse-root restart prod, /usr/local/sbin/omnicourse-root restart stag, /usr/local/sbin/omnicourse-root dump prod, /usr/local/sbin/omnicourse-root dump stag
SUDO
chmod 440 /etc/sudoers.d/omnicourse
visudo -cf /etc/sudoers.d/omnicourse >/dev/null

# 6. One systemd unit per environment, capped so it cannot crowd out other services.
install -o root -g root -m 644 "$HERE/omnicourse@.service" /etc/systemd/system/omnicourse@.service
systemctl daemon-reload
for spec in "${ENVS[@]}"; do read -r env _ _ <<<"$spec"; systemctl enable "omnicourse@$env" >/dev/null 2>&1; done

# 7. nginx: Cloudflare-only origin gate, then one server block per environment.
{
  echo "# Generated by deploy/server/setup.sh from https://www.cloudflare.com/ips-v4 and ips-v6."
  echo 'geo $realip_remote_addr $omnicourse_via_cloudflare {'
  echo '    default 0;'
  echo '    127.0.0.1/32 1;'
  echo '    ::1/128 1;'
  for list in ips-v4 ips-v6; do curl -fsSL "https://www.cloudflare.com/$list" | sed -E 's|^(.+)$|    \1 1;|'; done
  echo '}'
} >/etc/nginx/conf.d/omnicourse-cloudflare-origin.conf
for spec in "${ENVS[@]}"; do
  read -r env host port <<<"$spec"
  site="/etc/nginx/sites-available/omnicourse-$env.conf"
  sed -e "s|__HOST__|$host|g" -e "s|__PORT__|$port|g" -e "s|__ENV__|$env|g" "$HERE/nginx-site.conf" >"$site"
  # Keep the TLS lines certbot added on an earlier run.
  if [[ -f "/etc/letsencrypt/live/$host/fullchain.pem" ]]; then
    sed -i -e "s|# __TLS__ ||" "$site"
  fi
  ln -sfn "$site" "/etc/nginx/sites-enabled/omnicourse-$env.conf"
done
# Other sites share this nginx: if the new files break the config, remove them before anything reloads.
if ! nginx -t 2>/tmp/omnicourse-nginx-test.log; then
  cat /tmp/omnicourse-nginx-test.log >&2
  rm -f /etc/nginx/conf.d/omnicourse-cloudflare-origin.conf /etc/nginx/sites-enabled/omnicourse-*.conf
  echo "nginx config test failed: OmniCourse's nginx files removed, nothing reloaded" >&2
  exit 1
fi
systemctl reload nginx

echo "setup done. Next: deploy/server/add-deploy-key.sh <prod|stag> '<public key>', then certbot (deploy/README.md)."

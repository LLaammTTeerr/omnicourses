import { fileURLToPath } from 'node:url';
import { defineConfig, type UserConfig } from '@hey-api/openapi-ts';

// ADR 0018: the frontend's API types are generated from the committed contract, src/backend/openapi.json, into one
// module the generator owns (src/api-schema/types.gen.ts, committed so a build needs no generation step). Regenerate
// with `npm run generate:api -w src/frontend` after `npm run openapi -w src/backend`; api-schema.spec.ts fails while
// the committed module is stale.

export const CONTRACT = fileURLToPath(new URL('../backend/openapi.json', import.meta.url));
export const API_SCHEMA_DIR = fileURLToPath(new URL('./src/api-schema', import.meta.url));

/** Types only: no client, no SDK, nothing that runs. `output` is a folder the generator empties on every run. */
export const apiSchemaConfig = (output: string): UserConfig => ({
  input: CONTRACT,
  output: {
    path: output,
    entryFile: false,
    header: ['// Generated by @hey-api/openapi-ts from src/backend/openapi.json (ADR 0018). Do not edit by hand:', '// run `npm run generate:api -w src/frontend`.'],
  },
  plugins: ['@hey-api/typescript'],
  logs: { file: false, level: 'warn' },
});

export default defineConfig(apiSchemaConfig(API_SCHEMA_DIR));
